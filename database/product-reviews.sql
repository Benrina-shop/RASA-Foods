-- Run once in the Supabase SQL Editor for the project in supabase-config.js.
-- Review photos are compressed and stored in the review row so product deletion
-- cascades away the review text, customer details, and photo bytes together.
begin;

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  author_name text not null check (length(btrim(author_name)) between 1 and 120),
  author_email text not null check (length(btrim(author_email)) between 3 and 320),
  rating smallint not null check (rating between 1 and 5),
  comment text not null check (length(btrim(comment)) between 1 and 3000),
  images jsonb not null default '[]'::jsonb
    check (jsonb_typeof(images) = 'array' and jsonb_array_length(images) <= 3),
  created_at timestamptz not null default now(),
  constraint reviews_images_size_limit check (pg_column_size(images) <= 512 * 1024)
);

-- Tighten the limits when this script is re-run on a table created earlier.
-- NOT VALID preserves existing rows while enforcing the limit on new reviews.
alter table public.reviews drop constraint if exists reviews_images_check;
alter table public.reviews add constraint reviews_images_check
  check (jsonb_typeof(images) = 'array' and jsonb_array_length(images) <= 3) not valid;
alter table public.reviews drop constraint if exists reviews_images_size_limit;
alter table public.reviews add constraint reviews_images_size_limit
  check (pg_column_size(images) <= 512 * 1024) not valid;

create index if not exists reviews_product_created_idx
  on public.reviews (product_id, created_at desc);

alter table public.reviews enable row level security;
revoke all on public.reviews from public, anon, authenticated;

-- Storefronts can read the public review fields, but customer email remains private.
grant select (id, product_id, author_name, rating, comment, images, created_at)
  on public.reviews to anon, authenticated;
grant insert (product_id, author_name, author_email, rating, comment, images)
  on public.reviews to anon, authenticated;

drop policy if exists "Anyone can read product reviews without emails" on public.reviews;
create policy "Anyone can read product reviews without emails"
  on public.reviews for select to anon, authenticated
  using (true);

drop policy if exists "Visitors can submit product reviews" on public.reviews;
create policy "Visitors can submit product reviews"
  on public.reviews for insert to anon, authenticated
  with check (true);

comment on table public.reviews is
  'Product reviews. author_email is write-only for storefront API roles; images contain compressed photo data and are removed on product deletion.';

notify pgrst, 'reload schema';
commit;
